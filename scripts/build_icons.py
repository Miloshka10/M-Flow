"""Regenerate decorative CSS masks from the same SVGs used by the server."""
from pathlib import Path
import sys
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from interface import _ICONS, icon


def build():
    lines = ['/* Generated by scripts/build_icons.py; edit interface._ICONS. */', ':root {']
    for name in _ICONS:
        svg = icon(name).replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" ').replace('currentColor', 'black')
        lines.append(f'  --ui-symbol-{name}:url("data:image/svg+xml,{quote(svg, safe="")}");')
    lines.append('}')
    for name in _ICONS:
        lines.append(f'[data-ui-icon="{name}"] {{ --ui-control-symbol:var(--ui-symbol-{name}); }}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    (ROOT / 'static' / 'icon-symbols.css').write_text(build(), encoding='utf-8')
